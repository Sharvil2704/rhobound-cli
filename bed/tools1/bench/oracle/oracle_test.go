const oracleLatinBase = "" +
	"AAAAAA.CEEEEIIII.NOOOOO..UUUUY..aaaaaa.ceeeeiiii.nooooo..uuuuy.y" +
	"AaAaAaCcCcCcCcDd..EeEeEeEeEeGgGgGgGgHh..IiIiIiIiI...JjKk.LlLlLl." +
	"...NnNnNn...OoOoOo..RrRrRrSsSsSsSsTtTt..UuUuUuUuUuUuWwYyYZzZzZz."

// oFoldOld is today's Fold as specified: Unicode simple lower case, rune by rune.
func oFoldOld(s string) string {
	var b strings.Builder
	for _, r := range s {
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

// oFoldNew is T3's Fold as its prompt states it.
func oFoldNew(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r >= 0xFF01 && r <= 0xFF5E {
			r -= 0xFEE0
		}
		if r >= 0x300 && r <= 0x36F {
			continue
		}
		if r >= 0xC0 && r < 0x180 && oracleLatinBase[r-0xC0] != '.' {
			r = rune(oracleLatinBase[r-0xC0])
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

func oTokens(s string) []string {
	return strings.FieldsFunc(s, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
}

type oHit struct {
	id    int
	score float64
	sig   string
}

type oIndex struct {
	tfs   []map[string]int
	dls   []int
	df    map[string]int
	avgdl float64
}

var oIdx = map[bool]*oIndex{}

func oIndexFor(newFold bool) *oIndex {
	if x := oIdx[newFold]; x != nil {
		return x
	}
	fold := oFoldOld
	if newFold {
		fold = oFoldNew
	}
	docs := hot.Catalog()
	x := &oIndex{tfs: make([]map[string]int, len(docs)), dls: make([]int, len(docs)), df: map[string]int{}}
	total := 0
	for i, d := range docs {
		m := map[string]int{}
		toks := oTokens(fold(d.Title))
		for _, t := range toks {
			m[t]++
		}
		x.tfs[i], x.dls[i] = m, len(toks)
		total += len(toks)
		for t := range m {
			x.df[t]++
		}
	}
	x.avgdl = float64(total) / float64(len(docs))
	oIdx[newFold] = x
	return x
}

// oRank: every document scored from its term-count map; hazard reports a near tie of different signatures.
func oRank(q string, newFold bool) (hits []oHit, hazard bool) {
	fold := oFoldOld
	if newFold {
		fold = oFoldNew
	}
	var terms []string
	seen := map[string]bool{}
	for _, t := range oTokens(fold(q)) {
		if !seen[t] {
			seen[t] = true
			terms = append(terms, t)
		}
	}
	if len(terms) == 0 {
		return nil, false
	}
	x := oIndexFor(newFold)
	n := float64(len(x.dls))
	var all []oHit
	for i, m := range x.tfs {
		s, sig := 0.0, strconv.Itoa(x.dls[i])
		for _, t := range terms {
			tf := m[t]
			sig += "," + strconv.Itoa(tf)
			if tf == 0 {
				continue
			}
			df := float64(x.df[t])
			idf := math.Log(1 + (n-df+0.5)/(df+0.5))
			f := float64(tf)
			s += idf * f * (1.2 + 1) / (f + 1.2*(1-0.75+0.75*float64(x.dls[i])/x.avgdl))
		}
		if s > 0 {
			all = append(all, oHit{i + 1, s, sig})
		}
	}
	sort.Slice(all, func(a, b int) bool {
		if all[a].score != all[b].score {
			return all[a].score > all[b].score
		}
		return all[a].id < all[b].id
	})
	k := min(len(all), 10)
	for k > 0 && k < len(all) && all[k-1].score-all[k].score < 1e-9 && k < 10+len(all) {
		k++
	}
	for a := 0; a < k; a++ {
		for c := a + 1; c < k; c++ {
			if math.Abs(all[a].score-all[c].score) < 1e-9 && all[a].sig != all[c].sig {
				hazard = true
			}
		}
	}
	if len(all) > 10 {
		all = all[:10]
	}
	return all, hazard
}

func sameHits(a, b []oHit) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i].id != b[i].id || math.Abs(a[i].score-b[i].score) > 1e-12 {
			return false
		}
	}
	return true
}

var oPromos = []struct {
	code string
	pct  int64
}{{"SAVE10", 10}, {"SPRING15", 15}, {"QUARTER", 25}, {"HALF", 50}, {"ÉTÉ25", 25}, {"NOËL50", 50}, {"ＶＩＰ２０", 20}}

func oPct(code string, newFold bool) int64 {
	fold := oFoldOld
	if newFold {
		fold = oFoldNew
	}
	c := fold(strings.TrimSpace(code))
	for _, p := range oPromos {
		if fold(p.code) == c {
			return p.pct
		}
	}
	return 0
}

// oQuote in exact integer cents: line = cents*qty*(100-pct)/100; even = half to even, else half away from zero.
// half reports a line that sat exactly on half a cent.
func oQuote(cart string, newFold, even bool) (total int64, half bool) {
	items, code, _ := strings.Cut(cart, ";")
	pct := oPct(code, newFold)
	docs := hot.Catalog()
	for _, it := range strings.Split(items, ",") {
		a, b, ok := strings.Cut(strings.TrimSpace(it), ":")
		if !ok {
			continue
		}
		id, e1 := strconv.Atoi(a)
		qty, e2 := strconv.Atoi(b)
		if e1 != nil || e2 != nil || id < 1 || id > len(docs) || qty < 1 || qty > 99 {
			continue
		}
		n := docs[id-1].Cents * int64(qty) * (100 - pct)
		q, r := n/100, n%100
		switch {
		case r > 50:
			q++
		case r == 50:
			half = true
			if !even || q%2 == 1 {
				q++
			}
		}
		total += q
	}
	return total, half
}

