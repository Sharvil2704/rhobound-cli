type rankCase struct {
	q    string
	hits []oHit
}

type quoteCase struct {
	cart  string
	cents int64
}

type foldCase struct{ in, out string }

func fmtRank(name string, cs []rankCase) string {
	var b strings.Builder
	fmt.Fprintf(&b, "var %s = []hiddenRankCase{\n", name)
	for _, c := range cs {
		ids, sc := []string{}, []string{}
		for _, h := range c.hits {
			ids = append(ids, strconv.Itoa(h.id))
			sc = append(sc, strconv.FormatFloat(h.score, 'g', -1, 64))
		}
		fmt.Fprintf(&b, "\t{%q, []int{%s}, []float64{%s}},\n", c.q, strings.Join(ids, ", "), strings.Join(sc, ", "))
	}
	b.WriteString("}\n\n")
	return b.String()
}

func fmtQuote(name string, cs []quoteCase) string {
	var b strings.Builder
	fmt.Fprintf(&b, "var %s = []hiddenQuoteCase{\n", name)
	for _, c := range cs {
		fmt.Fprintf(&b, "\t{%q, %d},\n", c.cart, c.cents)
	}
	b.WriteString("}\n\n")
	return b.String()
}

func fmtFold(name string, cs []foldCase) string {
	var b strings.Builder
	fmt.Fprintf(&b, "var %s = []hiddenFoldCase{\n", name)
	for _, c := range cs {
		fmt.Fprintf(&b, "\t{%+q, %+q},\n", c.in, c.out)
	}
	b.WriteString("}\n\n")
	return b.String()
}

// fingerprint of the workload's inputs (catalog, query log, the generators' first draws)
func fingerprint() string {
	h := sha256.New()
	for _, d := range hot.Catalog() {
		fmt.Fprintf(h, "%d\t%s\t%d\n", d.ID, d.Title, d.Cents)
	}
	for _, q := range hot.QueryLog() {
		fmt.Fprintf(h, "%s\n", q)
	}
	qg, cg := hot.NewQueryGen(4242), hot.NewCartGen(4242)
	for i := 0; i < 64; i++ {
		fmt.Fprintf(h, "%s\n%s\n", qg.Next(), cg.Next())
	}
	return fmt.Sprintf("%x", h.Sum(nil))
}

