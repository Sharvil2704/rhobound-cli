// oracle_test.go: the rbd-bench oracle (kit only: tools1/bench/oracle/, never in the repo, never shown to a model).
// gen.sh copies it into a scratch copy of kshop/app/internal/hot (TODAY's code: repo/ main) and runs TestOracleGen
// there with ORACLE_OUT=DIR; it writes DIR/<task>/hidden_test.go for T1-rank, T2-round, T3-fold and T4-base.
//
// Independence: the answers come from brute-force references written from the tasks' statements (oRank: maps per
// document, no shared code with rank.go; oQuote: exact integer cents, both rounding rules; oFoldNew: the accent table
// made by foldtable.py from Python's unicodedata). Only the INPUTS come from the package: the catalog, the query log
// and the seeded generators (their fingerprint is itself a PASS_TO_PASS test). The oracle also checks itself against
// today's package (oRank with today's fold must equal hot.Rank; oQuote with today's rounding must equal hot.Quote).
//
// Order-proof goldens: a task's hidden tests must not depend on which other task merged first, so
//   - T1 (rank, PASS_TO_PASS) and T4 use only queries whose answer is the same under today's fold and T3's;
//   - T2 (round) uses only carts whose promotion matches the same way under both folds;
//   - T3 (fold) and T4 use only carts with no half-cent line (the same total under both rounding rules);
//   - a query is dropped when two of its top hits (or the 10th and any later hit) score within 1e-9 of each other
//     with different (dl, tf...) signatures: such an order could differ by one ulp across CPUs (FMA on arm64).

