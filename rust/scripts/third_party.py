"""Writes THIRD-PARTY.md: every third-party crate of the workspace, with its licence as its Cargo metadata
declares it (`cargo tree -f {l}`), split by where it ends up: in the `rbfast` binary (default features), in the
MIT/Apache-2.0-only build (`--no-default-features --features miniz`), only at build time (proc macros), or only in
tests, examples and the parity drivers (dev-dependencies and the crates' own driver binaries).
    cd rust && python3 -I scripts/third_party.py > THIRD-PARTY.md"""
import json
import subprocess

TREE = ["cargo", "tree", "--prefix", "none", "--no-dedupe", "-f", "{p}|{l}"]


def tree(*args):
    out = subprocess.run(TREE + list(args), capture_output=True, text=True, check=True).stdout
    pk = {}
    for ln in out.splitlines():
        if "|" not in ln:
            continue
        p, lic = ln.split("|", 1)
        p = p.replace(" (*)", "").replace(" (proc-macro)", "").strip()
        if "(/" in p:  # a workspace crate
            continue
        name, ver = p.split(" ")[:2]
        pk[(name, ver.lstrip("v"))] = lic.strip() or "NOT DECLARED"
    return pk


runtime = tree("-p", "rbfast", "-e", "normal,no-proc-macro")
miniz = tree("-p", "rbfast", "-e", "normal,no-proc-macro", "--no-default-features", "--features", "miniz")
build_all = tree("-p", "rbfast", "-e", "normal,build")
build_only = {k: v for k, v in build_all.items() if k not in runtime}
everything = tree("--workspace", "-e", "normal,build,dev")
everything.update(tree("--workspace", "-e", "normal,build,dev", "--features", "rbfast-otlp/miniz"))
dev_only = {k: v for k, v in everything.items() if k not in runtime and k not in build_only and k not in miniz}
miniz_extra = {k: v for k, v in miniz.items() if k not in runtime}
# every package of Cargo.lock (cargo metadata resolves for all platforms), and those no build above uses
meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], capture_output=True,
                                 text=True, check=True).stdout)
locked = {(p["name"], p["version"]): p.get("license") or "NOT DECLARED" for p in meta["packages"] if p["source"]}
lock_only = {k: v for k, v in locked.items() if k not in runtime and k not in miniz and k not in build_only
             and k not in dev_only}

why = {
    "rayon": "the work-stealing thread pool (reader, inference, model sweeps)",
    "rayon-core": "rayon's pool",
    "crossbeam-deque": "rayon's work-stealing queues",
    "crossbeam-epoch": "rayon's memory reclamation",
    "crossbeam-utils": "rayon's atomics",
    "either": "rayon",
    "memchr": "line and substring search in the reader",
    "flate2": "raw inflate for .gz captures (the gzip framing is rbfast-otlp's)",
    "zlib-rs": "flate2's default inflate backend here (a Rust port of zlib-ng)",
    "miniz_oxide": "flate2's pure-Rust backend (`--no-default-features --features miniz`)",
    "adler2": "miniz_oxide",
    "simd-adler32": "miniz_oxide",
    "crc32fast": "flate2's CRC-32",
    "cfg-if": "crc32fast",
    "serde_core": "serde_json's data model",
    "serde_json": "the tests' oracle files; rbfast-math's `oracle` feature (its parity driver)",
    "itoa": "serde_json",
    "zmij": "serde_json's float formatting",
}


def table(pk, reason=None):
    out = ["| crate | version | licence (Cargo metadata) | why |", "|---|---|---|---|"]
    for (name, ver), lic in sorted(pk.items()):
        out.append(f"| {name} | {ver} | {lic} | {reason or why.get(name, '')} |")
    return "\n".join(out)


lics = sorted(set(runtime.values()) | set(miniz.values()) | set(build_only.values()) | set(dev_only.values())
              | set(lock_only.values()))
print("""# Third-party crates

Generated by `scripts/third_party.py` from `cargo tree` (the licence column is each crate's own `license` field in
its Cargo metadata), and checked against `Cargo.lock`. The rbfast crates themselves are Apache-2.0, except the code
derived from the Go standard library (BSD-3-Clause, Copyright The Go Authors: [LICENSE-GO](LICENSE-GO); each such
file says which Go file it is derived from): rbfast-math's ports of Go's `math` functions (with the SunPro notices
for the FreeBSD-derived ones, in `crates/math/src/gomath.rs`) and of strconv's float layouts and `ParseFloat`,
rbfast-gostr's `strconv.Quote`, `IsPrint` (its tables generated from Go's source), `unicode` and `utf8` functions,
rbfast-otlp's `strconv` number parsing, `encoding/json` syntax rules, `compress/gzip` header reading and
`path.Clean`, rbfast-infer's `slices.SortFunc` (pdqsort) and float layouts, and the CLI's `text/tabwriter`, `flag`
parsing and `os.MkdirAll`. rbfast-otlp's and rbfast-infer's FxHasher follows rustc-hash's (Apache-2.0 OR MIT,
Copyright The Rust Project Developers).

## In the `rbfast` binary (default features)
""")
print(table(runtime))
print("""
## Added in the MIT/Apache-2.0-only build (`--no-default-features --features miniz`, which drops zlib-rs)
""")
print(table(miniz_extra))
print("""
## Used only to build (proc macros and their dependencies; not in the binary)
""")
print(table(build_only) if build_only else "None.")
print("""
## Used only by tests, examples and the crates' parity drivers (dev-dependencies, not in the binary)
""")
print(table(dev_only) if dev_only else "None beyond the above.")
print("""
## In Cargo.lock only (never built)

serde_json and serde_core name these under `[target.'cfg(any())'.dependencies]`, a platform condition that never
holds (a version constraint), so Cargo records them in Cargo.lock but never builds or links them.
""")
print(table(lock_only, "not built (locked only)") if lock_only else "None.")
print(f"""
## Licences

Every crate above is under a permissive licence; the expressions are: {', '.join(f'`{x}`' for x in lics)}.
Where an expression offers a choice (`MIT OR Apache-2.0`), rbfast uses the crate under MIT or Apache-2.0. The tests
also read the oracle's `.gz` files with flate2's miniz_oxide backend (the second table) and its JSON with serde_json.

**One exception to "MIT or Apache-2.0": `zlib-rs` (licence `Zlib`)**, flate2's inflate backend in the default
build. The Zlib licence is permissive (it is the licence of zlib and zlib-ng), but it is neither MIT nor
Apache-2.0. For an MIT/Apache-2.0-only build, select the pure-Rust miniz_oxide backend instead (licence
`MIT OR Zlib OR Apache-2.0`, used as MIT or Apache-2.0; with adler2 `0BSD OR MIT OR Apache-2.0` and
simd-adler32 `MIT`):

    cargo build --release -p rbfast --no-default-features --features miniz

It gives the same results; it was measured 1.6x slower on gzipped captures, and some corrupt deflate streams are
then refused as "gzip: invalid checksum" rather than with Go's "flate: corrupt input before offset N".
`memchr` is `Unlicense OR MIT` (used as MIT).
""")
