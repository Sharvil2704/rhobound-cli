// Writes crates/cli/src/tabwriter_cases.rs: Go's text/tabwriter output for each case, as Rust test data.
//
//	go run . > ../../../crates/cli/src/tabwriter_cases.rs
package main

import (
	"bytes"
	"fmt"
	"text/tabwriter"
)

type tc struct {
	minw, pad int
	right     bool
	in        string
}

func lit(b []byte) string {
	var s bytes.Buffer
	s.WriteString("b\"")
	for _, c := range b {
		switch {
		case c == '"':
			s.WriteString("\\\"")
		case c == '\\':
			s.WriteString("\\\\")
		case c >= 0x20 && c < 0x7f:
			s.WriteByte(c)
		default:
			fmt.Fprintf(&s, "\\x%02x", c)
		}
	}
	s.WriteString("\"")
	return s.String()
}

func main() {
	cases := []tc{
		{0, 1, false, "a\tb\tc\nxx\tyyy\n"},
		{0, 2, true, "service\trps\t\na *\t25.0\t\nbb\t1.5\t\n"},
		{0, 2, true, "x\ty\t\nsolo\nlonger\tz\t\nq"},
		{0, 2, true, "é\tb\t\nab\t\t\n"},
		{0, 2, true, "a\vb\tc\t\nxx\vyyy\tz\t\n"},
		{0, 2, true, "a\tb\fc\td\t\nlonger\tx\t\n"},
		{0, 2, true, "service\trps\t\ne\vd\fg *\t0.0\t1 x 1+\t\nother\t12.5\t3 x 2\t\n"},
		{0, 2, true, "a\u000bb\tc\t\n"},
		{0, 2, true, "a\u000cb\tc\t\nd\te\t\n"},
		{0, 2, false, "\xc3\tb\t\n\xe2\x82\xac\xff\tc\t\n"},
		{0, 2, true, "a\xffx\ty\xffz\tq\t\nab\tc\t\n"},
		{0, 2, true, "a\t\t\tb\t\n\t\tc\t\n"},
		{0, 2, true, "no newline\tat\tend"},
		{3, 1, false, "\f\f\n\n\t\n\v\v\n"},
		{0, 2, true, "k\vv\v\nkk\vvv\v\n\fk\tv\t\n"},
		{0, 2, true, "日本\tx\t\n\U0001f600\ty\t\n"},
	}
	fmt.Println("// SPDX-License-Identifier: Apache-2.0")
	fmt.Println("// Generated by scripts/go/tabwriter_cases (go run . > crates/cli/src/tabwriter_cases.rs) with Go's")
	fmt.Println("// text/tabwriter; do not edit. (minwidth, padding, AlignRight, input, Go's output)")
	fmt.Println("type Case = (usize, usize, bool, &'static [u8], &'static [u8]);")
	fmt.Println("#[rustfmt::skip]")
	fmt.Println("const GO_CASES: &[Case] = &[")
	for _, c := range cases {
		var out bytes.Buffer
		flags := uint(0)
		if c.right {
			flags = tabwriter.AlignRight
		}
		w := tabwriter.NewWriter(&out, c.minw, 8, c.pad, ' ', flags)
		w.Write([]byte(c.in))
		w.Flush()
		fmt.Printf("    (%d, %d, %v, %s, %s),\n", c.minw, c.pad, c.right, lit([]byte(c.in)), lit(out.Bytes()))
	}
	fmt.Println("];")
}
